//! Host shared-library lookup: `ldconfig -p`, falling back to scanning the
//! standard library directories. Never loads or executes the libraries.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::Serialize;

use super::paths::find_program;
use crate::host::{FileKind, Host, io_reason};

/// Libraries doctor looks up.
pub const WANTED: &[&str] = &[
    "libvulkan.so.1",
    "libEGL.so.1",
    "libGL.so.1",
    "libfuse.so.2",
];

pub const SCAN_DIRS: &[&str] = &[
    "/usr/lib64",
    "/usr/lib",
    "/lib64",
    "/lib",
    "/usr/lib/x86_64-linux-gnu",
    "/lib/x86_64-linux-gnu",
    "/usr/local/lib",
    "/run/opengl-driver/lib",
];

const LDCONFIG_DIRS: &[&str] = &["/sbin", "/usr/sbin", "/usr/bin"];

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum Source {
    Ldconfig,
    Scan,
    /// Lookup itself failed.
    None,
}

#[derive(Debug, Clone)]
pub struct LibIndex {
    pub source: Source,
    /// Why `ldconfig` was not used, if it was not.
    pub fallback_reason: Option<String>,
    found: BTreeMap<String, Option<PathBuf>>,
}

/// The `ldconfig -p` hwcap tag for our architecture.
fn arch_tag() -> Option<&'static str> {
    match std::env::consts::ARCH {
        "x86_64" => Some("x86-64"),
        "aarch64" => Some("AArch64"),
        _ => None,
    }
}

/// Parses `ldconfig -p` output into name → first path for our architecture.
/// Lines look like `\tlibGL.so.1 (libc6,x86-64) => /usr/lib/libGL.so.1`.
pub fn parse_ldconfig(output: &str, tag: Option<&str>) -> BTreeMap<String, PathBuf> {
    let mut map = BTreeMap::new();
    for line in output.lines() {
        let Some((lhs, path)) = line.split_once(" => ") else {
            continue;
        };
        let lhs = lhs.trim();
        let Some((name, flags)) = lhs.split_once(" (") else {
            continue;
        };
        let flags = flags.trim_end_matches(')');
        if let Some(tag) = tag
            && !flags.split(',').any(|f| f.trim() == tag)
        {
            continue;
        }
        map.entry(name.to_owned())
            .or_insert_with(|| PathBuf::from(path.trim()));
    }
    map
}

impl LibIndex {
    pub fn failed(reason: &str) -> Self {
        Self {
            source: Source::None,
            fallback_reason: Some(reason.to_owned()),
            found: BTreeMap::new(),
        }
    }

    pub fn build(host: &dyn Host, names: &[&str]) -> Self {
        let reason = match find_program(host, "ldconfig", LDCONFIG_DIRS) {
            None => "ldconfig not found".to_owned(),
            Some(prog) => match host.run(&prog, &["-p"]) {
                Ok(out) if out.success() => {
                    let map = parse_ldconfig(&out.stdout, arch_tag());
                    if map.is_empty() {
                        "ldconfig -p listed no libraries".to_owned()
                    } else {
                        let found = names
                            .iter()
                            .map(|&n| (n.to_owned(), map.get(n).cloned()))
                            .collect();
                        return Self {
                            source: Source::Ldconfig,
                            fallback_reason: None,
                            found,
                        };
                    }
                }
                Ok(out) => format!("ldconfig -p exited with {:?}", out.code),
                Err(e) => format!("ldconfig -p failed: {}", io_reason(&e)),
            },
        };
        let found = names
            .iter()
            .map(|&n| (n.to_owned(), scan(host, n)))
            .collect();
        Self {
            source: Source::Scan,
            fallback_reason: Some(reason),
            found,
        }
    }

    /// `None` if the library was not found (or not looked up).
    pub fn get(&self, name: &str) -> Option<&Path> {
        self.found.get(name).and_then(|p| p.as_deref())
    }
}

fn scan(host: &dyn Host, name: &str) -> Option<PathBuf> {
    SCAN_DIRS
        .iter()
        .map(|d| Path::new(d).join(name))
        .find(|p| host.metadata(p).is_ok_and(|m| m.kind == FileKind::File))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::testing::FakeHost;

    const LDCONFIG: &str = "\
1234 libs found in cache `/etc/ld.so.cache'
\tlibvulkan.so.1 (libc6,x86-64) => /usr/lib/libvulkan.so.1
\tlibGL.so.1 (libc6) => /usr/lib32/libGL.so.1
\tlibGL.so.1 (libc6,x86-64) => /usr/lib/libGL.so.1
\tlibEGL.so.1 (libc6,x86-64) => /usr/lib/libEGL.so.1
\tlibfoo.so (libc6,x86-64, OS ABI: Linux 3.2.0) => /usr/lib/libfoo.so
Cache generated by: ldconfig (GNU libc) stable release version 2.44
";

    #[test]
    fn parses_and_filters_32_bit() {
        let m = parse_ldconfig(LDCONFIG, Some("x86-64"));
        assert_eq!(m["libGL.so.1"], PathBuf::from("/usr/lib/libGL.so.1"));
        assert_eq!(
            m["libvulkan.so.1"],
            PathBuf::from("/usr/lib/libvulkan.so.1")
        );
        assert_eq!(m["libfoo.so"], PathBuf::from("/usr/lib/libfoo.so"));
        assert_eq!(m.len(), 4);
    }

    #[test]
    fn without_tag_first_entry_wins() {
        let m = parse_ldconfig(LDCONFIG, None);
        assert_eq!(m["libGL.so.1"], PathBuf::from("/usr/lib32/libGL.so.1"));
    }

    #[test]
    fn uses_ldconfig_when_it_works() {
        let mut h = FakeHost::new();
        h.file_mode("/sbin/ldconfig", "", 0o755)
            .command("/sbin/ldconfig", 0, LDCONFIG);
        let idx = LibIndex::build(&h, WANTED);
        assert_eq!(idx.source, Source::Ldconfig);
        assert_eq!(
            idx.get("libEGL.so.1"),
            Some(Path::new("/usr/lib/libEGL.so.1"))
        );
        assert_eq!(idx.get("libfuse.so.2"), None);
    }

    #[test]
    fn falls_back_to_scan_when_ldconfig_missing() {
        let mut h = FakeHost::new();
        h.file("/usr/lib/x86_64-linux-gnu/libGL.so.1", "");
        let idx = LibIndex::build(&h, WANTED);
        assert_eq!(idx.source, Source::Scan);
        assert_eq!(idx.fallback_reason.as_deref(), Some("ldconfig not found"));
        assert_eq!(
            idx.get("libGL.so.1"),
            Some(Path::new("/usr/lib/x86_64-linux-gnu/libGL.so.1"))
        );
        assert_eq!(idx.get("libvulkan.so.1"), None);
    }

    #[test]
    fn falls_back_when_ldconfig_lists_nothing() {
        // e.g. Alpine, where ldconfig does not maintain a cache.
        let mut h = FakeHost::new();
        h.file_mode("/sbin/ldconfig", "", 0o755)
            .command("/sbin/ldconfig", 0, "")
            .file("/usr/lib/libEGL.so.1", "");
        let idx = LibIndex::build(&h, WANTED);
        assert_eq!(idx.source, Source::Scan);
        assert_eq!(
            idx.get("libEGL.so.1"),
            Some(Path::new("/usr/lib/libEGL.so.1"))
        );
    }

    #[test]
    fn falls_back_when_ldconfig_fails() {
        let mut h = FakeHost::new();
        h.file_mode("/sbin/ldconfig", "", 0o755)
            .command_error("/sbin/ldconfig", "timed out after 3 s");
        let idx = LibIndex::build(&h, WANTED);
        assert_eq!(idx.source, Source::Scan);
        assert!(idx.fallback_reason.unwrap().contains("timed out"));
    }
}
